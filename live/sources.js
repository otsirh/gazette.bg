// Every source live.gazette.bg reads, with how much its word weighs.
//
// The weight is by checkable criteria, never by political line:
//   1 — first-hand: an institution's own channel, or the person speaking on
//       camera. Nothing stands between the reader and who said it.
//   2 — news agency or public broadcaster: bound by law to report and
//       correct, with a newsroom that answers for every item.
//   3 — editorial outlet with a known owner and signed articles.
//   4 — not verified by us, or mostly unsigned or re-posted text. Still read:
//       it shows what a part of the public is told, and it counts less.
// list: no feed; the source is its news list page, and this pattern picks
// the news links on it (dated items only).
// headlinesOnly: the site's terms forbid robots or text mining of its pages
// (or its host's do, like Substack's), so only its feed's headline and link
// are used; its article pages are never fetched.
// independent: a known journalist, commentator or small team without an
// outlet behind them. A named person answers for it, but no editor checks it.
// partisan: a party's or politician's own channel. First-hand for what they
// say, but what they say is their position, so it never confirms a story.
// A source is added only with a working feed and a reason for its weight,
// and only if its site lets AI use its content: robots.txt must not shut out
// Anthropic's agents (ClaudeBot, anthropic-ai, Claude-User) nor say
// ai-input=no. update.js checks this every day and skips a source that
// changes its mind. Who is added and who is removed follows the rules in
// SOURCES-POLICY.md; sources we want but may not read, and those declined
// (with the rule and the examples), are in watchlist.js.
// YouTube channels are read through the YouTube Data API (YOUTUBE_API_KEY),
// never through youtube.com's feeds, which its robots.txt disallows.
// onlyHost: the feed is shared by several papers of one publisher; only the
// items on this host are this source's.
// outlet: channels of one outlet share it ("nova"), so a story told on two
// of its channels still counts as one outlet, never as confirmation.
// viaBulgaria: the site turns away addresses outside Bulgaria (GitHub's
// servers are in the US), so in Actions it is read through the Mac mini.

